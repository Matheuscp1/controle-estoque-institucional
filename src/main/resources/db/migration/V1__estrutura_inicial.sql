CREATE TABLE orgaos (
  codigo VARCHAR(64) PRIMARY KEY CHECK (TRIM(codigo) <> ''),
  sigla VARCHAR(30) NOT NULL CHECK (TRIM(sigla) <> ''),
  nome VARCHAR(255) NOT NULL CHECK (TRIM(nome) <> ''),
  uf CHAR(2) NOT NULL
);
CREATE TABLE itens (
  codigo VARCHAR(64) PRIMARY KEY CHECK (TRIM(codigo) <> ''),
  descricao VARCHAR(500) NOT NULL CHECK (TRIM(descricao) <> ''),
  unidade VARCHAR(30) NOT NULL CHECK (TRIM(unidade) <> ''),
  saldo_inicial NUMERIC(19,3) NOT NULL CHECK (saldo_inicial >= 0),
  saldo NUMERIC(19,3) NOT NULL CHECK (saldo >= 0),
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  versao BIGINT NOT NULL DEFAULT 0 CHECK (versao >= 0),
  data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_externo VARCHAR(128) NOT NULL UNIQUE CHECK (TRIM(id_externo) <> ''),
  codigo_orgao VARCHAR(64) NOT NULL REFERENCES orgaos(codigo),
  solicitante VARCHAR(255) NOT NULL CHECK (TRIM(solicitante) <> ''),
  origem VARCHAR(20) NOT NULL CHECK (origem IN ('PORTAL','INTEGRACAO')),
  assinatura VARCHAR(64) NOT NULL,
  data_hora TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  situacao VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADO' CHECK (situacao IN ('CONFIRMADO','CANCELADO')),
  data_cancelamento TIMESTAMP WITH TIME ZONE,
  motivo_cancelamento VARCHAR(500),
  CHECK ((situacao = 'CONFIRMADO' AND data_cancelamento IS NULL AND motivo_cancelamento IS NULL)
    OR (situacao = 'CANCELADO' AND data_cancelamento IS NOT NULL AND motivo_cancelamento IS NOT NULL
      AND TRIM(motivo_cancelamento) <> '' AND data_cancelamento >= data_hora))
);
CREATE TABLE pedido_itens (
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
  codigo_item VARCHAR(64) NOT NULL REFERENCES itens(codigo),
  quantidade NUMERIC(19,3) NOT NULL CHECK (quantidade > 0),
  PRIMARY KEY (pedido_id, codigo_item)
);
CREATE INDEX idx_itens_unidade_saldo ON itens(unidade, saldo, codigo);
CREATE INDEX idx_itens_saldo ON itens(saldo, codigo);
CREATE INDEX idx_pedidos_orgao_data ON pedidos(codigo_orgao, data_hora DESC, id DESC);
CREATE INDEX idx_pedidos_orgao_situacao_data ON pedidos(codigo_orgao, situacao, data_hora DESC, id DESC);
