CREATE TABLE import_control (id INTEGER PRIMARY KEY, ready BOOLEAN NOT NULL DEFAULT FALSE, active_job VARCHAR(64));
INSERT INTO import_control(id,ready) VALUES (1,FALSE);
CREATE TABLE import_jobs (
 id VARCHAR(64) PRIMARY KEY, status VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, lease_until TIMESTAMP WITH TIME ZONE,
 total_batches INTEGER NOT NULL DEFAULT 0, duplicate_headers BIGINT NOT NULL DEFAULT 0, error TEXT,
 CHECK (status IN ('PREPARING','STAGING','NEEDS_REVIEW','COMPLETED','FAILED'))
);
CREATE TABLE import_batches (
 id VARCHAR(64) PRIMARY KEY, job_id VARCHAR(64) NOT NULL REFERENCES import_jobs(id),
 source VARCHAR(30) NOT NULL, batch_number INTEGER NOT NULL,
 payload TEXT NOT NULL, done BOOLEAN NOT NULL DEFAULT FALSE, attempts INTEGER NOT NULL DEFAULT 0,
 next_publish TIMESTAMP WITH TIME ZONE NOT NULL, error TEXT,
 UNIQUE(job_id,source,batch_number)
);
CREATE INDEX idx_import_batches_dispatch ON import_batches(done,next_publish);
CREATE INDEX idx_import_batches_job ON import_batches(job_id,done);
CREATE TABLE import_rows (
 job_id VARCHAR(64) NOT NULL REFERENCES import_jobs(id), source VARCHAR(30) NOT NULL,
 line_number BIGINT NOT NULL, record_key VARCHAR(128), reference_key VARCHAR(128),
 raw_payload TEXT NOT NULL, payload TEXT, error TEXT,
 PRIMARY KEY(job_id,source,line_number)
);
CREATE INDEX idx_import_rows_key ON import_rows(job_id,source,record_key,reference_key);
CREATE TABLE import_issues (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id VARCHAR(64) NOT NULL REFERENCES import_jobs(id), source VARCHAR(30) NOT NULL,
 line_number BIGINT, record_key VARCHAR(128), reason VARCHAR(1500) NOT NULL
);
CREATE INDEX idx_import_issues_job ON import_issues(job_id,id);
