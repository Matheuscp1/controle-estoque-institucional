ALTER TABLE import_rows ADD COLUMN excluded BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE import_issues ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
CREATE INDEX idx_import_issues_active ON import_issues(job_id,active,id);
CREATE INDEX idx_import_issues_record ON import_issues(job_id,active,source,record_key);
CREATE TABLE import_quarantine (
 job_id VARCHAR(64) NOT NULL REFERENCES import_jobs(id),
 entity_type VARCHAR(20) NOT NULL, record_key VARCHAR(128) NOT NULL,
 PRIMARY KEY(job_id,entity_type,record_key)
);
CREATE INDEX idx_import_quarantine_key ON import_quarantine(entity_type,record_key);
CREATE TABLE import_corrections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id VARCHAR(64) NOT NULL REFERENCES import_jobs(id), source VARCHAR(30) NOT NULL,
 line_number BIGINT NOT NULL, revision BIGINT NOT NULL,
 previous_payload TEXT, corrected_payload TEXT NOT NULL, justification VARCHAR(1000) NOT NULL,
 operation VARCHAR(20) NOT NULL DEFAULT 'CORRECT',
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(job_id,source,line_number,revision)
);
